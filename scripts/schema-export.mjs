import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import 'dotenv/config';
import pg from 'pg';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'supabase', 'production-snapshot.md');
const MIGRATIONS = path.join(ROOT, 'supabase', 'migrations');
const BASELINE = path.join(ROOT, 'supabase', 'schema_baseline.sql');

const QUERIES = {
  tables: `select table_schema as schema, table_name as name, table_type as type
    from information_schema.tables
    where table_schema in ('public', 'storage') and table_type in ('BASE TABLE', 'VIEW')
    order by 1, 2`,
  columns: `select table_name as tbl, column_name as name, data_type as type, is_nullable as nullable,
      coalesce(column_default, '') as dflt, is_generated as generated
    from information_schema.columns
    where table_schema = 'public'
    order by table_name, ordinal_position`,
  rls: `select c.relname as name, c.relrowsecurity as enabled, c.relforcerowsecurity as forced
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r'
    order by 1`,
  policies: `select schemaname as schema, tablename as tbl, policyname as name, cmd,
      array_to_string(roles, ',') as roles, coalesce(qual, '') as qual, coalesce(with_check, '') as check
    from pg_policies
    where schemaname in ('public', 'storage')
    order by 1, 2, 3`,
  functions: `select p.proname as name, pg_get_function_identity_arguments(p.oid) as args,
      p.prosecdef as definer, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f'
    order by 1, 2`,
  triggers: `select event_object_table as tbl, trigger_name as name, action_timing as timing,
      string_agg(event_manipulation, ' or ' order by event_manipulation) as events, action_statement as stmt
    from information_schema.triggers
    where trigger_schema = 'public'
    group by 1, 2, 3, 5
    order by 1, 2`,
  buckets: `select id, public, file_size_limit as size_limit,
      coalesce(array_to_string(allowed_mime_types, ','), '') as mime
    from storage.buckets
    order by 1`
};

function shortHash(text) {
  return crypto.createHash('sha256').update(text).digest('hex').slice(0, 12);
}

function cell(value) {
  return String(value).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

function table(headers, rows) {
  const lines = ['| ' + headers.join(' | ') + ' |', '|' + headers.map(() => '---').join('|') + '|'];
  for (const row of rows) lines.push('| ' + row.map(cell).join(' | ') + ' |');
  return lines.join('\n');
}

export function render(data) {
  const out = ['# Production schema snapshot', '', `Taken ${data.takenAt}. Generated by \`node scripts/schema-export.mjs\`; do not edit by hand.`, ''];
  out.push('## Tables and views', '', table(['Schema', 'Name', 'Type'], data.tables.map((t) => [t.schema, t.name, t.type])), '');
  out.push('## Row Level Security', '', table(['Table', 'Enabled', 'Forced'], data.rls.map((r) => [r.name, r.enabled, r.forced])), '');
  out.push('## Columns', '', table(['Table', 'Column', 'Type', 'Nullable', 'Default', 'Generated'],
    data.columns.map((c) => [c.tbl, c.name, c.type, c.nullable, c.dflt, c.generated])), '');
  out.push('## Policies', '', table(['Schema', 'Table', 'Policy', 'Command', 'Roles', 'Using', 'With check'],
    data.policies.map((p) => [p.schema, p.tbl, p.name, p.cmd, p.roles, p.qual, p.check])), '');
  out.push('## Functions', '', 'The hash changes whenever the function body changes.', '',
    table(['Function', 'Security definer', 'Body hash'], data.functions.map((f) => [`${f.name}(${f.args})`, f.definer, shortHash(f.def)])), '');
  out.push('## Triggers', '', table(['Table', 'Trigger', 'Timing', 'Events', 'Action'],
    data.triggers.map((t) => [t.tbl, t.name, t.timing, t.events, t.stmt])), '');
  out.push('## Storage buckets', '', table(['Bucket', 'Public', 'Size limit', 'Allowed types'],
    data.buckets.map((b) => [b.id, b.public, b.size_limit == null ? 'none' : b.size_limit, b.mime || 'any'])), '');
  return out.join('\n');
}

function readMigrationText() {
  const files = fs.readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();
  const parts = files.map((f) => fs.readFileSync(path.join(MIGRATIONS, f), 'utf8'));
  if (fs.existsSync(BASELINE)) parts.unshift(fs.readFileSync(BASELINE, 'utf8'));
  return parts.join('\n').toLowerCase();
}

const NAME = '(?:"([^"]+)"|(?:public\\.)?([a-z0-9_]+))';

function declared(sql, kind) {
  const patterns = {
    table: new RegExp(`create\\s+(?:table|(?:or\\s+replace\\s+)?(?:materialized\\s+)?view)\\s+(?:if\\s+not\\s+exists\\s+)?(?:public\\.)?${NAME}`, 'g'),
    policy: new RegExp(`create\\s+policy\\s+${NAME}`, 'g'),
    function: new RegExp(`create\\s+(?:or\\s+replace\\s+)?function\\s+(?:public\\.)?${NAME}`, 'g'),
    trigger: new RegExp(`create\\s+(?:or\\s+replace\\s+)?trigger\\s+${NAME}`, 'g')
  };
  const dropPatterns = {
    table: new RegExp(`drop\\s+(?:table|view|materialized\\s+view)\\s+(?:if\\s+exists\\s+)?(?:public\\.)?${NAME}`, 'g'),
    policy: new RegExp(`drop\\s+policy\\s+(?:if\\s+exists\\s+)?${NAME}`, 'g'),
    function: new RegExp(`drop\\s+function\\s+(?:if\\s+exists\\s+)?(?:public\\.)?${NAME}`, 'g'),
    trigger: new RegExp(`drop\\s+trigger\\s+(?:if\\s+exists\\s+)?${NAME}`, 'g')
  };
  const events = [];
  for (const m of sql.matchAll(patterns[kind])) events.push([m.index, 'create', m[1] || m[2]]);
  for (const m of sql.matchAll(dropPatterns[kind])) events.push([m.index, 'drop', m[1] || m[2]]);
  events.sort((a, b) => a[0] - b[0]);
  const live = new Set();
  for (const [, action, name] of events) {
    if (action === 'create') live.add(name);
    else live.delete(name);
  }
  return live;
}

export function drift(data, migrationSql) {
  const sql = migrationSql.toLowerCase();
  const prod = {
    table: new Set(data.tables.filter((t) => t.schema === 'public').map((t) => t.name.toLowerCase())),
    policy: new Set(data.policies.filter((p) => p.schema === 'public').map((p) => p.name.toLowerCase())),
    function: new Set(data.functions.map((f) => f.name.toLowerCase())),
    trigger: new Set(data.triggers.map((t) => t.name.toLowerCase()))
  };
  const report = {};
  for (const kind of Object.keys(prod)) {
    const inMigrations = declared(sql, kind);
    report[kind] = {
      onlyInProduction: [...prod[kind]].filter((n) => !sql.includes(n)).sort(),
      onlyInMigrations: [...inMigrations].filter((n) => !prod[kind].has(n)).sort()
    };
  }
  report.bucket = {
    onlyInProduction: data.buckets.map((b) => String(b.id).toLowerCase()).filter((id) => !sql.includes(`'${id}'`)).sort(),
    onlyInMigrations: []
  };
  return report;
}

async function main() {
  const url = process.env.SUPABASE_DB_URL;
  if (!url) {
    console.error('SUPABASE_DB_URL is not set. Add the Session pooler connection string from Supabase (Connect button) to .env.');
    process.exit(1);
  }
  const client = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await client.connect();
  const data = { takenAt: new Date().toISOString().slice(0, 10) };
  try {
    await client.query('begin read only');
    for (const [key, sql] of Object.entries(QUERIES)) data[key] = (await client.query(sql)).rows;
    await client.query('rollback');
  } finally {
    await client.end();
  }
  fs.writeFileSync(OUT, render(data) + '\n');
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
  const report = drift(data, readMigrationText());
  let issues = 0;
  for (const [kind, r] of Object.entries(report)) {
    for (const name of r.onlyInProduction) { console.log(`In production, not in any migration: ${kind} ${name}`); issues++; }
    for (const name of r.onlyInMigrations) { console.log(`In migrations, missing from production (not applied?): ${kind} ${name}`); issues++; }
  }
  console.log(issues ? `${issues} difference(s) to check by hand.` : 'Production matches the migrations by name.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
